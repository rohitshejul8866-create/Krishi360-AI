import { Download, ScrollText, ShieldCheck } from 'lucide-react'
import { Button } from '../../components/ui/Button'
import { Badge } from '../../components/ui/Badge'
import { formatDateTime } from '../../services/utils'
import { useToast } from '../../context/ToastContext'
import { useApp } from '../../services/store'
import { AdminCollectionPage, type AdminFilter } from './AdminCollectionPage'
import type { Column } from '../../components/ui/Table'

type Log = ReturnType<typeof useApp>['auditLogs'][number]

const roleFilter: AdminFilter<Log> = { label: 'Role', options: ['farmer', 'expert', 'admin'], value: (row) => row.role }

export function AuditLogsPage() {
  const { auditLogs, backendConnected } = useApp()
  const { show } = useToast()

  const exportCsv = () => {
    const header = 'ID,Timestamp,Actor,Role,Action,Target\n'
    const escape = (value: string) => `"${value.replace(/"/g, '""')}"`
    const body = auditLogs
      .map((log) => [log.id, log.timestamp, log.actor, log.role, log.action, log.target].map(escape).join(','))
      .join('\n')
    const url = URL.createObjectURL(new Blob([header + body], { type: 'text/csv;charset=utf-8' }))
    const link = document.createElement('a')
    link.href = url
    link.download = 'krishi360-demo-audit-log.csv'
    document.body.appendChild(link)
    link.click()
    link.remove()
    URL.revokeObjectURL(url)
    show('Audit log exported', 'A CSV of demo activity was downloaded.')
  }

  const columns: Column<Log>[] = [
    { key: 'time', label: 'When', render: (row) => <div><p className="font-semibold text-ink">{formatDateTime(row.timestamp)}</p><p className="text-xs text-muted">{row.id}</p></div> },
    { key: 'actor', label: 'Actor', render: (row) => <div><p className="font-bold text-ink">{row.actor}</p><p className="text-xs capitalize text-muted">{row.role}</p></div> },
    { key: 'action', label: 'Action', render: (row) => row.action },
    { key: 'target', label: 'Target', render: (row) => <span className="text-sm text-muted">{row.target}</span> },
  ]

  return (
    <AdminCollectionPage
      eyebrow="Governance"
      title="Audit logs"
      description="Review activity records fetched from the backend API and generated by portal actions."
      rows={auditLogs}
      columns={columns}
      searchable={(row) => [row.actor, row.action, row.target, row.role, row.id]}
      filters={[roleFilter]}
      stats={[
        { label: 'Events', value: auditLogs.length, detail: 'Recorded in backend', icon: <ScrollText size={18} />, tone: 'sage' },
        { label: 'Admin actions', value: auditLogs.filter((log) => log.role === 'admin').length, detail: 'Platform-side events', icon: <ShieldCheck size={18} />, tone: 'forest' },
        { label: 'Latest event', value: auditLogs[0] ? formatDateTime(auditLogs[0].timestamp) : '—', detail: 'Latest timestamp', icon: <ScrollText size={18} />, tone: 'neutral' },
        { label: 'Persistence', value: backendConnected ? 'Backend API' : 'Session', detail: backendConnected ? 'Synced via /api/audit-logs' : 'Local fallback', icon: <ShieldCheck size={18} />, tone: backendConnected ? 'forest' : 'alert' },
      ]}
      detailTitle={(row) => row.action}
      detailContent={(row) => (
        <div className="grid gap-4 sm:grid-cols-2">
          <div><p className="text-xs font-bold uppercase tracking-wide text-muted">Event ID</p><p className="font-semibold text-ink">{row.id}</p></div>
          <div><p className="text-xs font-bold uppercase tracking-wide text-muted">Timestamp</p><p className="font-semibold text-ink">{formatDateTime(row.timestamp)}</p></div>
          <div><p className="text-xs font-bold uppercase tracking-wide text-muted">Actor</p><p className="font-semibold text-ink">{row.actor}</p></div>
          <div><p className="text-xs font-bold uppercase tracking-wide text-muted">Role</p><Badge tone="sage" className="capitalize">{row.role}</Badge></div>
          <div><p className="text-xs font-bold uppercase tracking-wide text-muted">Action</p><p className="font-semibold text-ink">{row.action}</p></div>
          <div><p className="text-xs font-bold uppercase tracking-wide text-muted">Target</p><p className="font-semibold text-ink">{row.target}</p></div>
        </div>
      )}
      actions={<Button size="sm" variant="outline" onClick={exportCsv}><Download size={14} /> Export CSV</Button>}
      emptyMessage="No audit events match the current filters."
    />
  )
}
